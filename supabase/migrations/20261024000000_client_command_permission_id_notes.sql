-- Extend command permission IDs with safe renaming, runtime aliases, and Founder-managed notes.
alter table public.client_command_rank_permissions
  drop constraint if exists client_command_rank_permissions_permission_key_fkey;
alter table public.client_command_rank_permissions
  add constraint client_command_rank_permissions_permission_key_fkey
  foreign key (permission_key) references public.client_command_permission_catalog(permission_key)
  on update cascade on delete cascade;

alter table public.client_command_user_overrides
  drop constraint if exists client_command_user_overrides_permission_key_fkey;
alter table public.client_command_user_overrides
  add constraint client_command_user_overrides_permission_key_fkey
  foreign key (permission_key) references public.client_command_permission_catalog(permission_key)
  on update cascade on delete cascade;

create table if not exists public.client_command_permission_aliases (
  alias_key text primary key,
  permission_key text not null references public.client_command_permission_catalog(permission_key)
    on update cascade on delete cascade,
  created_at timestamptz not null default now(),
  constraint client_command_permission_alias_key_format check (alias_key ~ '^[a-z][a-z0-9_.-]{0,99}$')
);
create index if not exists client_command_permission_aliases_permission_idx
  on public.client_command_permission_aliases(permission_key);

create table if not exists public.client_command_permission_notes (
  id bigint generated by default as identity primary key,
  permission_key text not null references public.client_command_permission_catalog(permission_key)
    on update cascade on delete cascade,
  note text not null check (length(trim(note)) > 0 and length(note) <= 1000),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists client_command_permission_notes_key_id_idx
  on public.client_command_permission_notes(permission_key, id);

alter table public.client_command_permission_aliases enable row level security;
alter table public.client_command_permission_notes enable row level security;
revoke all on public.client_command_permission_aliases from anon, authenticated;
revoke all on public.client_command_permission_notes from anon, authenticated;
